import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const context={window:{}};
vm.runInNewContext(read('assets/vitruvia-evidence.js'),context);
const d=context.window.VitruviaEvidence;
const classify=x=>d.classify(x).key;
assert.equal(classify({type:'manuscript',link:'https://example.org/record'}),'witness');
assert.equal(classify({type:'passage',latin:'Architectura'}),'edition-text');
assert.equal(classify({type:'edition',meta:'Traducción histórica · francés'}),'translation');
assert.equal(classify({type:'edition',meta:'edición documentada'}),'edition');
assert.equal(classify({type:'book',readable:false}),'bibliography');
assert.equal(classify({type:'book',readable:true}),'reader');
assert.equal(classify({type:'article',doi:'10.1234/sample'}),'article-index');
assert.equal(classify({type:'article',source:'OpenAlex'}),'article-index');
assert.equal(classify({type:'wikipedia'}),'reference');
assert.match(d.label({type:'article',doi:'10.1234/sample'},'es'),/registro bibliográfico/);
assert.doesNotMatch(d.label({type:'edition'},'es'),/crítica|cotejada/);
assert.doesNotMatch(d.label({type:'passage'},'es'),/manuscrito original/);
const main=read('assets/vitruvia-search.js'),html=read('vitruvia.html');
assert.match(main,/VitruviaEvidence\?\.classify\(d\)/);
assert.match(main,/VitruviaEvidence\?\.label\(d,S\.lang\)/);
assert.ok(html.includes('assets/vitruvia-evidence.js'));
assert.ok(html.indexOf('assets/vitruvia-evidence.js')<html.indexOf('assets/vitruvia-search.js'));
new vm.Script(main);
console.log('PASS: source-level evidence labels distinguish records, translations, identified texts and original witnesses');
