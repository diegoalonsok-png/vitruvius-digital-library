import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const src=readFileSync('assets/apparatus-catalog.mjs','utf8');
const begin=src.indexOf('const fold='),end=src.indexOf('let entries=',begin);
assert(begin>=0&&end>begin,'Lexical matching utilities must exist');
const ctx={};
vm.runInNewContext(src.slice(begin,end)+'\nthis.lookup={lexicalTerms,containsWholeTerms,exactPosition};',ctx);
const {lexicalTerms,containsWholeTerms,exactPosition}=ctx.lookup;
const terms=lexicalTerms('logos');
assert.equal(containsWholeTerms('astrólogos',terms),false);
assert.equal(containsWholeTerms('LOGOS, λόγος; logós',terms),true);
assert.equal(containsWholeTerms('logos astrólogos',terms),true);
assert.equal(containsWholeTerms('astrologos',terms),false);
assert.equal(exactPosition('astrólogos','logos'),null);
assert.equal(exactPosition('λόγος: discurso','λογος').start,0);
const notes=readFileSync('assets/critical-search.mjs','utf8');
assert(notes.includes('return queryWords.every(word=>words.has(word));'),'Critical notes must match complete words');
const shared=readFileSync('assets/kurilo-apparatus.js','utf8');
assert(shared.includes('if(words.has(t))hit++'),'Shared apparatus must match whole words');
const site=readFileSync('assets/site-bar.js','utf8');
assert(site.includes('panel.style.left='),'Typography panel must be positioned relative to viewport');
console.log('PASS: logos does not match astrólogos; Greek accents and typography popover covered.');
