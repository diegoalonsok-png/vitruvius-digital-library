import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
const load=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const imageEngine=load("assets/vitruvia-image-engine-v2.js");
const transport=load("assets/vitruvia-data.js");
new vm.Script(imageEngine);new vm.Script(transport);
const start=imageEngine.indexOf("async function getJSON("),end=imageEngine.indexOf("function imageParams(",start);
assert.ok(start>=0&&end>start);
const extracted=imageEngine.slice(start,end);
const make=(window,fetch)=>vm.runInNewContext(extracted+";getJSON",{window,fetch,URLSearchParams,Error});
let calls=0;const requested=[];
const w={VitruviaData:{remoteJSON:async (url,options)=>{calls++;requested.push({url,options});return {query:{pages:{}}};}}};
const fn=make(w,()=>{throw Error("Should use shared transport")});
const signal=new AbortController().signal;
await fn({action:"query",generator:"search",gsrsearch:"Pythagoras"},signal);
assert.equal(calls,1);
assert.equal(requested[0].options.signal,signal);
assert.equal(requested[0].options.timeoutMs,9000);
assert.equal(requested[0].options.maxAge,120000);
assert.match(requested[0].url,/^https:\/\/commons\.wikimedia\.org\/w\/api\.php\?/);
assert.match(requested[0].url,/gsrsearch=Pythagoras/);
assert.match(requested[0].url,/origin=\*/);
const fallback=make({},async()=>({ok:true,json:async()=>({query:{pages:{}}})}));
assert.ok((await fallback({action:"query",generator:"search",gsrsearch:"Cicero"},signal)).query);
assert.match(transport,/cooldowns\.set\(/);
assert.match(transport,/const active=pending\.get\(key\)/);
assert.match(transport,/signal\?\.aborted/);
console.log("PASS: Wikimedia uses bounded shared transport, cancellation, cooldown and fallback");
