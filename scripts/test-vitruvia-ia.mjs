import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';

const html=fs.readFileSync('vitruvia-ia.html','utf8');
const body=html.split('<body>')[1]?.split('<script type="module">')[0]||'';
const scripts=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].filter(x=>x[1].trim());
assert.equal(scripts.length,1,'Buscar hoy must contain one self-contained application script');
assert.doesNotThrow(()=>new vm.Script(scripts[0][1],{filename:'buscar-hoy.js'}),'Invalid JavaScript syntax');
assert.match(html,/<title>Buscar hoy<\/title>/,'Minimal title missing');
assert.match(body,/<h1>Buscar hoy<\/h1>/,'Editorial search heading missing');
assert.match(html,/font:italic 400 clamp\(/,'Vitruvia serif typography missing');
assert.doesNotMatch(body,/<header\b|<nav\b|<button\b|role="button"/i,'No visible branding, menus or buttons on the Grok-like screen');
assert.match(body,/id="question"/,'Single prompt missing');
assert.match(body,/id="file"[^>]+type="file"/,'Accessible document attachment control missing');
assert.match(html,/\.pdf,\.docx,\.txt/,'PDF and DOCX are mandatory');
assert.match(body,/id="conversation"/,'Documentary result surface missing');
assert.doesNotMatch(html,/<meta\s+http-equiv="refresh"/i,'Page must no longer redirect away');
assert.match(scripts[0][1],/addEventListener\('drop'/,'Drag and drop files must work without visible buttons');
assert.match(scripts[0][1],/addEventListener\('paste'/,'Pasted files must work without visible buttons');
assert.match(scripts[0][1],/event\.shiftKey&&event\.key\.toLowerCase\(\)==='o'/,'Accessible keyboard file picker missing');
assert.match(scripts[0][1],/event\.key==='Backspace'/,'Keyboard deletion of the session is mandatory');
assert.match(scripts[0][1],/e\.key==='Enter'/,'Enter must submit queries');
assert.match(scripts[0][1],/window\.addEventListener\('pagehide'/,'Clear ephemeral data on closing tab');
assert.match(scripts[0][1],/documentData=null/,'Document content must remain erasable');
assert.doesNotMatch(scripts[0][1],/api\.github\.com|github\.com\/repos|localStorage|sessionStorage|indexedDB/,'Uploaded files must not be stored in GitHub or browser persistence');
const front=fs.readFileSync('vitruvia.html','utf8');
assert.match(front,/href="vitruvia-ia\.html"/,'Navigation from Vitruvia must link to Buscar hoy');
console.log('PASS Buscar hoy: minimal editorial interface, document ingestion, keyboard accessibility and no-persistence privacy checks');
