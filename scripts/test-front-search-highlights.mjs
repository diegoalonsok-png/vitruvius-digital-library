import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {parallelHighlight,parallelExcerpt} from "../assets/parallel-highlights.mjs";
const corpus=JSON.parse(readFileSync("data/structured/recensio-es.json","utf8"));
const p=corpus.passages.find(p=>p.locus==="1.2.1");
assert.ok(p&&p.latin.includes("decore")&&p.translation.includes("decoro"),"Original edition changed or locus missing");
const latin=parallelHighlight(p.latin,{query:"decor",lang:"la",latin:p.latin});
const spanish=parallelHighlight(p.translation,{query:"decor",lang:"es",latin:p.latin});
assert.equal(latin.direct,1);
assert.match(latin.html,/<mark class="search-hit search-hit-literal"[^>]*>decore<\/mark>/);
assert.equal(spanish.equivalent,1);
assert.match(spanish.html,/<mark class="search-hit search-hit-equivalent"[^>]*>decoro<\/mark>/);
assert.equal(parallelHighlight("La fachada tiene decoro",{query:"decor",lang:"es",latin:"Architectura est opus"}).equivalent,0,"No inventar una equivalencia no atestiguada");
assert.equal(parallelHighlight(p.latin,{query:"symmetria",lang:"la",latin:p.latin}).direct,1);
const app=readFileSync("assets/app.js","utf8"),home=readFileSync("index.html","utf8");
assert.match(app,/parallel-highlights\.mjs\?v=20261117-search-decor-highlight-v8/);
assert.match(home,/assets\/app\.js\?v=20261117-search-term-highlights-v4/);
assert.match(home,/#search-results \.result-parallel mark\.search-hit/);
console.log("PASS front search: decor → decore (Latin) + decoro (Spanish), symmetria and stylesheet/cache references");
