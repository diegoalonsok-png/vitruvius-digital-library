import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const code=read('assets/vitruvia-photo-background.js');
const css=read('assets/vitruvia-photo-background.css');
const html=read('vitruvia.html');
const window={};
const document={readyState:'loading',addEventListener(){}};
vm.runInNewContext(code,{window,document,console},{timeout:1000});
assert(code.includes("document.getElementById('front-background-panel')"),'Photo controls must be inside existing colour palette');
assert(code.includes("u.protocol!=='https:'||u.username||u.password"),'Only HTTPS URLs with no credentials are allowed');
assert(code.includes('image.onload')&&code.includes('image.onerror'),'Do not apply broken images');
assert(code.includes('file.size>8*1024*1024'),'Local files must have a size limit');
assert(code.includes('allowed.has(file.type)'),'Only images are allowed');
assert(code.includes('URL.createObjectURL(file)'),'Local photo uses browser object URL');
assert(code.includes('URL.revokeObjectURL(objectURL)'),'Revoke local file object URL');
assert(code.includes("localStorage.removeItem(key)"),'Local file must not persist or leak');
assert(code.includes("ui.opacity.addEventListener('input',setVeil)"),'Overlay must be adjustable');
assert(code.includes("https://commons.wikimedia.org/wiki/Special:MediaSearch?type=image"),'Official external image search missing');
assert(css.includes('html[data-reading-photo=true] body'),'Visitor photo style must only apply when selected');
assert(css.includes('var(--vr-photo-veil)'),'Photo must have readability overlay');
assert(css.includes('@media print'),'Printing must not include a background photo by default');
assert(html.includes('assets/vitruvia-photo-background.js?v=20261104-photo-bg-v1'));
assert(html.includes('assets/vitruvia-photo-background.css?v=20261104-photo-bg-v1'));
console.log('PASS: optional private image backgrounds with safe HTTPS, local upload, overlay and reset');
