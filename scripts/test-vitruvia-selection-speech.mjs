import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=name=>readFileSync(new URL('../'+name,import.meta.url),'utf8');
const js=read('assets/vitruvia-selection-speech.js');
const css=read('assets/vitruvia-selection-speech.css');
const html=read('vitruvia.html');
const window={};
const document={readyState:'loading',addEventListener(event,cb){
 assert.equal(event,'DOMContentLoaded');
 assert.equal(typeof cb,'function');
}};
vm.runInNewContext(js,{window,document,console}, {timeout:1000});
const split=window.VitruviaSelectionSpeech?.splitText;
assert.equal(typeof split,'function');
assert.equal(window.VitruviaSelectionSpeech.version,'2.0-site-wide');
assert.deepEqual(Array.from(split('')),[]);
assert.deepEqual(Array.from(split('Un párrafo corto.')),['Un párrafo corto.']);
const long=Array(160).fill('palabras latinas para estudiar textos').join(' ');
const parts=Array.from(split(long,140));
assert(parts.length>10);
assert(parts.every(p=>p.length<=140),'Speech synthesis must be chunked into bounded utterances');
assert.equal(parts.join(' '),long);
assert(js.includes("ui.hidden=true"),'Speech player must be hidden before selection');
assert(js.includes("selection.isCollapsed"),'Speech player must require non-collapsed selection');
assert(js.includes("root.contains(parent)"),'Do not read inputs, browser UI, or external elements');
assert(js.includes("document.addEventListener('selectionchange',schedule)"),'Text selection detection must work without permanent controls');
assert(js.includes("document.addEventListener('touchend',schedule"),'Touch selection must work');
assert(js.includes("play.addEventListener('click'"),'Play button missing');
assert(js.includes("pause.addEventListener('click'"),'Pause/resume button missing');
assert(js.includes("stop.addEventListener('click'"),'Stop button missing');
assert(js.includes("window.addEventListener('vitruvia:search'")===false||js.includes("['vitruvia:search','vitruvia:clear']"),'Speech must stop on new search');
assert(css.includes('.vr-selection-speech[hidden]'),'Hidden state must be enforced visually');
assert(html.includes('assets/vitruvia-selection-speech.css?v=20261104-selected-paragraph-audio-v1'));
assert(html.includes('assets/vitruvia-selection-speech.js?v=20261104-selected-paragraph-audio-v1'));
assert(!js.includes('fetch(')&&!js.includes('XMLHttpRequest'), 'Text-to-speech must not directly transmit selected content');
console.log('PASS: contextual text-to-speech stays hidden until selection, chunks paragraphs and supports mobile / stop / pause');
