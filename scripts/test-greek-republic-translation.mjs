#!/usr/bin/env node
/** Candado: la traducción histórica alojada nunca reemplaza el griego. */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => JSON.parse(readFileSync(new URL('../' + path, import.meta.url), 'utf8'));
const base = 'data/classics-corpus/';
const greek = read(base + 'plato-republic-grc.json');
const english = read(base + 'plato-republic-en.json');
const registry = read(base + 'search-registry.json');
const catalogue = read('data/bibliotheca-graeca-latina-I-bce-I-ce.json');
const fiches = read(base + 'bibliotheca-academic-fiches-2026-11-16.json');
const keys = records => new Set(records.map(p => String(p.locus || '').split(':').at(-1)));
assert.equal(greek.language, 'grc');
assert.equal(english.language, 'en');
assert.equal(english.sourceType, 'historical-translation-tei');
assert.equal(english.alignmentStatus, 'stephanus-page');
assert.equal(english.passages.length, 278);
assert.equal(keys(english.passages).size, 278);
assert.deepEqual([...keys(english.passages)].sort(), [...keys(greek.passages)].sort(), 'Every Greek Stephanus reference must have an English counterpart');
assert.ok(english.passages.every(p => p.text.length > 60 && !/<[^>]*>/.test(p.text)));
assert.equal(registry.count, registry.entries.length);
assert.equal(registry.entries.filter(p => p.workId === 'plato-republic' && p.language === 'grc').length, 1);
assert.equal(registry.entries.filter(p => p.workId === 'plato-republic' && p.language === 'en').length, 1);
const work = catalogue.works.find(w => w.id === 'plato-republic');
assert.equal(work?.corpusFiles?.en, base + 'plato-republic-en.json');
assert.equal(work?.corpusFiles?.grc, base + 'plato-republic-grc.json');
assert.equal(work?.sourceRegistration?.translationHosted, true);
const fiche = fiches.records.find(w => w.workId === 'plato-republic');
assert.ok(fiche?.textualIndex?.readers?.some(r => r.language === 'en' && r.source === base + 'plato-republic-en.json'));
console.log('OK: griego intacto; 278 loci únicos con versión histórica inglesa; lector y catálogos sincronizados.');
