import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const entries=JSON.parse(read('data/onomasticon-vitruvianum.json')).entities;
const context={window:{}};
vm.runInNewContext(read('assets/vitruvia-historical-names.js'),context);
const H=context.window.VitruviaHistoricalNames;
const arch=H.find('arquimedes',entries);
assert.equal(arch[0].id,'archimedes');
assert.equal(H.find('archimedes',entries)[0].id,'archimedes');
assert.equal(H.find('Ἀρχιμήδης',entries)[0].id,'archimedes');
assert.equal(H.labels(arch[0]).latin,'Archimedes');
assert.equal(H.labels(arch[0]).greek,'Ἀρχιμήδης');
const pit=H.find('pitagoras',entries);
assert.equal(pit[0].id,'pythagoras');
assert.equal(H.labels(pit[0]).greek,'Πυθαγόρας');
assert.equal(H.find('arquimedes gasparotto junior',entries).length,0);
assert.equal(H.find('cafetera',entries).length,0);
const html=read('vitruvia.html'),js=read('assets/vitruvia-search.js'),understand=read('assets/vitruvia-understand.js');
assert.ok(html.indexOf('assets/vitruvia-historical-names.js')<html.indexOf('assets/vitruvia-search.js'));
assert.match(html,/overflow-wrap:anywhere/);
assert.match(html,/search-preview \.sp-ancient-names/);
assert.match(js,/VitruviaHistoricalNames\?\.find\(q,S\.people\)/);
assert.match(js,/function previewHistorical\(person\)/);
assert.match(js,/if\(historical\[0\]\)previewHistorical\(historical\[0\]\)/);
assert.match(understand,/const intellectual=\/filosof/);
assert.match(understand,/const ancient=\/antigu/);
new vm.Script(js);new vm.Script(understand);
console.log('Historical names and unclipped autocomplete previews pass');
