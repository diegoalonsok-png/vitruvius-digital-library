import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const js=read('assets/vitruvia-visual-import.js');
const css=read('assets/vitruvia-visual-import.css');
const page=read('vitruvia.html');
const window={};
const document={readyState:'loading',addEventListener(name,handler){
 assert.equal(name,'DOMContentLoaded');
 assert.equal(typeof handler,'function');
}};
vm.runInNewContext(js,{window,document,console,URL},{timeout:1500});
const api=window.VitruviaVisualImport;
assert.equal(api.version,'1.0');
assert.equal(api.filenameQuery('Marco_Aurelio.jpg'),'Marco Aurelio');
assert.equal(api.filenameQuery('De-rerum-natura.pdf'),'De rerum natura');
assert.equal(api.filenameQuery('IMG_20261104.jpg'),'');
assert.equal(api.filenameQuery('123456.jpg'),'');
assert.equal(api.filenameQuery('screenshot.png'),'');
assert.equal(api.directPhotoURL('https://upload.wikimedia.org/path/photo.jpg'),'https://upload.wikimedia.org/path/photo.jpg');
assert.equal(api.directPhotoURL('http://site.org/pic.jpg'),null);
assert.equal(api.directPhotoURL('https://user:pass@example.com/pic.jpg'),null);
assert.equal(api.directPhotoURL('https://example.com/pic.jpg?token=secret'),null);
assert.equal(api.directPhotoURL('https://example.com/pic.svg'),null);
assert.equal(api.directPhotoURL('https://example.com/page.html'),null);
const executable=js.replace(/\/\*[\s\S]*?\*\//g,'').replace(/^\s*\/\/.*$/gm,'');
assert(!/\b(?:localStorage|sessionStorage|indexedDB)\s*[.[]|\b(?:fetch|XMLHttpRequest|sendBeacon|toDataURL|readAsDataURL)\s*\(/.test(executable),'No persistence, upload, or base64 conversion');
assert(js.includes('URL.createObjectURL(file)'),'Object URL is needed only for local temporary preview');
assert(js.includes('URL.revokeObjectURL(prev)'),'Temporary blob must be revoked after search or close');
assert(js.includes("ui.photoInput.value=''")&&js.includes("ui.docInput.value=''"),'File inputs must be cleared');
assert(js.includes("ui.thumb.removeAttribute('src')"),'Image DOM source must be removed');
assert(js.includes("selection=null"),'File reference must be released');
assert(js.includes('discard({clearDescription:true});close({reset:false})'),'Search and external Lens should discard prior image');
assert(js.includes("window.addEventListener('pagehide'"),'Navigation must clear image');
assert(js.includes("document.addEventListener('visibilitychange'"),'Background tabs must clear images');
assert(js.includes("window.addEventListener(name,()=>close())"),'Search and reset must clear images');
assert(js.includes("form.addEventListener('submit',()=>close(),true)"),'All search submits must clear images');
assert(js.includes("window.VitruviaVisualImport={filenameQuery,directPhotoURL,version:'1.0'}"),'Public API must not expose raw file bytes');
assert(js.includes('https://lens.google.com/'),'Visual recognition is explicitly routed to optional external service');
assert(js.includes('https://lens.google.com/')&&js.includes('Ningún archivo se envía desde Vitruvia'),'No silent external upload');
assert(css.includes('.vr-visual-panel[hidden]'),'Panel starts hidden');
assert(page.includes('id="vr-visual-add"')&&page.includes('id="vr-visual-camera"'),'Both icons must be in the real search form');
assert(page.includes('assets/vitruvia-visual-import.js?v=20261104-private-pdf-v2'));
assert(page.includes('assets/vitruvia-visual-import.css?v=20261104-private-pdf-v2'));
const searchForm=page.slice(page.indexOf('<form class="searchform"'),page.indexOf('</form>',page.indexOf('<form class="searchform"')));
assert(searchForm.includes('id="vr-visual-camera"')&&searchForm.includes('id="vr-visual-add"'),'Icons must be inside form');
assert(searchForm.indexOf('id="vr-visual-camera"')<searchForm.indexOf('id="submit"'),'Camera must precede submit button');
console.log('PASS: ephemeral per-visitor visual attachments, explicit Lens consent, memory cleanup and no server upload');
