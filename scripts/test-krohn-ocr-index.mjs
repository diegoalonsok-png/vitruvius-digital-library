import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const text=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const registry=JSON.parse(text("data/classics-corpus/search-registry.json"));
const coverage=JSON.parse(text("data/classics-corpus/coverage-audit.json"));
const ocr=JSON.parse(text("data/text/krohn-1912.json"));
const entry=registry.entries.find(e=>e.workId==="krohn-1912-pdf");
assert.equal(entry?.format,"historical-ocr-pages");
assert.equal(entry.path,"data/text/krohn-1912.json");
assert.equal(entry.language,"la");
assert.equal(ocr.length,314);
assert.deepEqual(ocr.map(r=>r.page),Array.from({length:314},(_,i)=>i+1));
assert(ocr.some(r=>/architectura/i.test(r.text)),"OCR has no Latin architecture term");
const report=coverage.works.find(w=>w.id==="krohn-1912-pdf");
assert(report?.indexedTextFiles.includes(entry.path));
assert(/OCR/.test(report.notes),"Coverage must warn about OCR, not claim critical transcription");
const search=text("assets/classics-corpus-search.js");
assert(search.includes("historical-ocr-pages"));
assert(search.includes("Página OCR"));
assert(search.includes("OCR HISTÓRICO"));
const histor=text("assets/historical-search.mjs");
assert(histor.includes('new URLSearchParams(location.search)'));
assert(histor.includes('get("page")'));
assert(histor.includes('get("ed")'));
assert(histor.includes('get("q")'));
console.log("PASS: Krohn 1912 searchable page OCR is explicitly non-critical and deep-linked");
