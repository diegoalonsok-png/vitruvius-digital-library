import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const context={window:{}};
vm.runInNewContext(readFileSync(new URL('../assets/vitruvia-discovery.js',import.meta.url),'utf8'),context);
const d=context.window.VitruviaDiscovery;
const band=d.plan('Radiohead',{canonical:'Radiohead',authorityDescription:'English rock band',instanceOf:['Q5741069']});
assert.equal(band.kind,'music-group');
assert.ok(band.queries.some(q=>q.includes('concert')));
const mock=(title)=>({title:'File:'+title,imageinfo:[{extmetadata:{}}]});
const photo=d.imageRank(mock('Radiohead live concert in London.jpg'),band);
const logo=d.imageRank(mock('Radiohead wordmark vector.svg'),band);
assert.equal(photo.accepted,true);
assert.ok(photo.score>logo.score);
const items=[{name:'Radiohead logo',group:'context',score:1000},{name:'Radiohead concert',group:'live',score:100},{name:'Radiohead group photograph',group:'live',score:90}];
assert.equal(d.previewImages(items,band)[0].group,'live');
const person=d.plan('Cicerón',{canonical:'Cicerón',kind:'person',birthYear:-106});
assert.equal(person.kind,'person');
console.log('Music-group image ranking and non-music regression checks passed.');
